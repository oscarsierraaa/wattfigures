#!/usr/bin/env node
/*
  fetch-fonts.mjs — self-host the configured Google Fonts. Downloads the
  latin + latin-ext woff2 subsets and writes assets/fonts/*.woff2 plus
  assets/fonts.css (@font-face pointing at the local files). Why: EU court
  rulings treat Google Fonts CDN hits as a GDPR issue, local fonts are
  faster, and the CSP gets to drop two third-party hosts (breachfolio
  pattern). Used when theme.selfHostFonts is true; rerun any time with
  `npm run fonts:fetch` inside a generated site.
*/
import { writeFileSync, mkdirSync, readFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// A modern-browser UA makes Google return woff2 sources.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

export async function fetchFonts({ fontSans, fontMono, assetsDir }) {
  const fam = f => f.trim().replace(/\s+/g, '+');
  const cssUrl = 'https://fonts.googleapis.com/css2?family=' + fam(fontSans) +
    ':wght@400;500;600;700&family=' + fam(fontMono) + ':wght@400;500&display=swap';
  const res = await fetch(cssUrl, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error('Google Fonts CSS HTTP ' + res.status);
  const css = await res.text();

  // Google emits "/* <subset> */" before each @font-face — keep latin + latin-ext.
  const blocks = css.split(/\/\* /).filter(b => /^latin(-ext)? \*\//.test(b)).map(b => '/* ' + b);
  if (!blocks.length) throw new Error('no latin subsets found in Google Fonts CSS');
  const fontsDir = path.join(assetsDir, 'fonts');
  mkdirSync(fontsDir, { recursive: true });
  let out = '/* Self-hosted Google Fonts (latin + latin-ext) — generated by tools/fetch-fonts.mjs */\n';
  const seen = new Map();
  for (let block of blocks) {
    const family = (block.match(/font-family:\s*'([^']+)'/) || [, 'font'])[1];
    const weight = (block.match(/font-weight:\s*(\d+)/) || [, '400'])[1];
    const subset = (block.match(/^\/\* (latin(?:-ext)?) \*\//) || [, 'latin'])[1];
    for (const [, url] of block.matchAll(/url\((https:[^)]+\.woff2)\)/g)) {
      if (!seen.has(url)) {
        const name = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight}-${subset}.woff2`;
        const r = await fetch(url);
        if (!r.ok) throw new Error('woff2 HTTP ' + r.status + ': ' + url);
        writeFileSync(path.join(fontsDir, name), Buffer.from(await r.arrayBuffer()));
        seen.set(url, name);
      }
      block = block.split(url).join('fonts/' + seen.get(url));
    }
    out += block.trim() + '\n';
  }
  writeFileSync(path.join(assetsDir, 'fonts.css'), out, 'utf-8');
  return { files: [...seen.values()] };
}

// CLI: run from a generated site (tools/ is copied into it).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const cfg = JSON.parse(readFileSync(path.join(ROOT, 'site.config.json'), 'utf-8'));
  const theme = cfg.theme || {};
  fetchFonts({
    fontSans: theme.fontSans || 'Inter',
    fontMono: theme.fontMono || 'JetBrains Mono',
    assetsDir: path.join(ROOT, 'assets'),
  }).then(r => console.log(`fonts: ${r.files.length} woff2 self-hosted + assets/fonts.css`))
    .catch(e => { console.error('fonts: FAILED — ' + e.message + '\n  Retry with network, or set theme.selfHostFonts to false and re-scaffold.'); process.exit(1); });
}
